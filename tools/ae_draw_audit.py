"""ae_draw_audit - procedural-draw census per mission (RPE6 Phase 3, P3-M3).

    python tools/ae_draw_audit.py [--mission m1,m2,m3,m4,m5] [--min 6] [--md docs/engine/audit/draw_census.md]

For every function in ``src/missions/<m>/*.py`` and ``src/cutscenes/<m>*.py``
counts, by AST:
  draw   ``pygame.draw.*`` / ``gfxdraw.*`` / ``pd.*`` primitive calls (procedural)
  blit   ``.blit(`` / ``.blits(`` calls (surface composition)
  art    calls into the loaded/baked art tier: ``artpack.*``, ``art.get``/``_art.get``,
         ``_m5art(``, ``sprites.*``, ``get_sprite(``, ``pose(`` (cached) - i.e. already converted
  cache  ``pose(``/``_cache``-style render-once helpers inside the function
Ranks functions by procedural draw calls so conversion work starts at the top.
The "converted share" per mission is art / (art + draw): the Phase 3 target
(>= 80 % of procedural draw calls in M1-M4 moved to baked blits) is measured
against this number. Also reports D5 (raw loads outside engine/assets).

Generalises tools/m5_draw_audit.py (kept as a wrapper).
"""
from __future__ import annotations

import argparse
import ast
import glob
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = re.compile(r"pygame\.image\.load\(|pygame\.mixer\.Sound\(|pygame\.mixer\.music\.load\(")
ART_NAMES = {"artpack", "art", "_art", "_m5art", "sprites", "_sprites", "sprite_lib", "_maru_art"}
ART_FUNCS = {"_m5art", "get_sprite", "pose", "blit_frame", "blit9slice", "_guard_rot", "_maru_pose", "_art_or"}


def _files(mission: str) -> list[Path]:
    fs = sorted(glob.glob(str(ROOT / "src" / "missions" / mission / "*.py")))
    fs += sorted(glob.glob(str(ROOT / "src" / "cutscenes" / f"{mission}*.py")))
    return [Path(f) for f in fs]


def _classify(call: ast.Call) -> str | None:
    f = call.func
    if isinstance(f, ast.Attribute):
        v = f.value
        if isinstance(v, ast.Attribute) and v.attr in ("draw", "gfxdraw"):
            return "draw"
        if isinstance(v, ast.Name) and v.id in ("draw", "gfxdraw", "pd"):
            return "draw"
        if f.attr in ("blit", "blits"):
            return "blit"
        if isinstance(v, ast.Name) and v.id in ART_NAMES:
            return "art"
        if isinstance(v, ast.Attribute) and v.attr in ART_NAMES:
            return "art"
        if f.attr in ART_FUNCS:
            return "art"
    elif isinstance(f, ast.Name) and f.id in ART_FUNCS:
        return "art"
    return None


def census(mission: str) -> list[dict]:
    rows = []
    for f in _files(mission):
        try:
            tree = ast.parse(f.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        rel = f.relative_to(ROOT).as_posix()
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            c = {"draw": 0, "blit": 0, "art": 0}
            for sub in ast.walk(node):
                if isinstance(sub, ast.Call):
                    k = _classify(sub)
                    if k:
                        c[k] += 1
            if any(c.values()):
                rows.append({"file": rel, "func": node.name, "line": node.lineno,
                             "len": (node.end_lineno or node.lineno) - node.lineno + 1, **c})
    rows.sort(key=lambda r: (-r["draw"], r["file"], r["line"]))
    return rows


def raw_loads() -> list[str]:
    hits = []
    for p in (ROOT / "src").rglob("*.py"):
        rel = p.relative_to(ROOT).as_posix()
        if rel.startswith("src/engine/assets/"):
            continue
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if RAW.search(line) and not line.lstrip().startswith("#"):
                hits.append(f"{rel}:{i}")
    return hits


def summarise(rows: list[dict]) -> dict:
    d = sum(r["draw"] for r in rows)
    b = sum(r["blit"] for r in rows)
    a = sum(r["art"] for r in rows)
    return {"funcs": len(rows), "draw": d, "blit": b, "art": a,
            "converted_share": (a / (a + d)) if (a + d) else 0.0,
            "top": rows[:15]}


def render_md(data: dict[str, dict], raw: list[str], min_calls: int) -> str:
    out = ["# Procedural draw census (RPE6 Phase 3, P3-M3)", "",
           "Generated by `python tools/ae_draw_audit.py --md docs/engine/audit/draw_census.md`. "
           "Counts are AST call sites per function (not per frame). `draw` = `pygame.draw`/`gfxdraw` "
           "primitives (procedural), `blit` = surface composition, `art` = calls into the baked/loaded "
           "tier (`artpack`, `art.get`, `_m5art`, `get_sprite`, `pose` ...). "
           "**Converted share = art / (art + draw)** - the Phase 3 >= 80 % target for M1-M4 is read off this column.", "",
           "| mission | functions | draw calls | blits | art-tier calls | converted share |",
           "|---|---:|---:|---:|---:|---:|"]
    for m, s in data.items():
        out.append(f"| {m} | {s['funcs']} | {s['draw']} | {s['blit']} | {s['art']} | {s['converted_share']:.1%} |")
    tot_d = sum(s["draw"] for s in data.values())
    tot_a = sum(s["art"] for s in data.values())
    out.append(f"| **all** | {sum(s['funcs'] for s in data.values())} | {tot_d} | "
               f"{sum(s['blit'] for s in data.values())} | {tot_a} | {(tot_a / (tot_a + tot_d)) if tot_a + tot_d else 0:.1%} |")
    out += ["", f"D5 - raw `pygame.image.load` / `mixer.Sound` / `music.load` outside `src/engine/assets`: **{len(raw)}**"]
    for h in raw:
        out.append(f"- `{h}`")
    for m, s in data.items():
        out += ["", f"## {m} - top functions by procedural draw calls (>= {min_calls})", "",
                "| draw | blit | art | function | lines |", "|---:|---:|---:|---|---:|"]
        for r in s["top"]:
            if r["draw"] < min_calls:
                continue
            out.append(f"| {r['draw']} | {r['blit']} | {r['art']} | `{r['file']}:{r['line']}` `{r['func']}` | {r['len']} |")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mission", default="m1,m2,m3,m4,m5")
    ap.add_argument("--min", type=int, default=6)
    ap.add_argument("--md")
    ap.add_argument("--top", type=int, default=15)
    args = ap.parse_args(argv)
    data = {}
    for m in args.mission.split(","):
        rows = census(m.strip())
        s = summarise(rows)
        s["top"] = rows[: args.top]
        data[m.strip()] = s
        print(f"{m}: funcs={s['funcs']} draw={s['draw']} blit={s['blit']} art={s['art']} converted={s['converted_share']:.1%}")
        for r in rows[: args.top]:
            if r["draw"] >= args.min:
                print("  %4d draw %3d blit %3d art  %s:%d %s (len %d)" % (
                    r["draw"], r["blit"], r["art"], r["file"], r["line"], r["func"], r["len"]))
    raw = raw_loads()
    print(f"D5 raw loads outside engine/assets: {len(raw)}")
    for h in raw:
        print("  ", h)
    if args.md:
        Path(args.md).write_text(render_md(data, raw, args.min), encoding="utf-8", newline="\n")
        print("wrote", args.md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
