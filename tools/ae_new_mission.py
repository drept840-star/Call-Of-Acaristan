# ── update ──────────────────────────────────────────────────────────────


def _advance_down(keys) -> bool:
    return bool(keys[pygame.K_SPACE] or keys[pygame.K_RETURN])


def _move_player(keys):
    p = STATE.player
    if p is None:
        return
    dx = (keys[pygame.K_d] or keys[pygame.K_RIGHT]) - (keys[pygame.K_a] or keys[pygame.K_LEFT])
    dy = (keys[pygame.K_s] or keys[pygame.K_DOWN]) - (keys[pygame.K_w] or keys[pygame.K_UP])
    if dx and dy:
        dx, dy = dx * 0.7071, dy * 0.7071
    speed = 3.0
    r = p.rect
    r.x += int(round(dx * speed))
    for w in STATE.walls:
        if r.colliderect(w):
            r.x = w.left - r.w if dx > 0 else w.right
    r.y += int(round(dy * speed))
    for w in STATE.walls:
        if r.colliderect(w):
            r.y = w.top - r.h if dy > 0 else w.bottom
    if dx or dy:
        p.angle = math.atan2(dy, dx)


def _step_bullets():
    p = STATE.player
    keep = []
    for b in STATE.bullets:
        b["x"] += b["dx"]
        b["y"] += b["dy"]
        b["life"] -= 1
        if b["life"] <= 0:
            continue
        if any(w.collidepoint(b["x"], b["y"]) for w in STATE.walls):
            continue
        if p is not None and b.get("owner") == "enemy":
            if (b["x"] - p.rect.centerx) ** 2 + (b["y"] - p.rect.centery) ** 2 < 18 ** 2:
                p.hp -= b.get("damage", 8)
                continue
        keep.append(b)
    STATE.bullets = keep


def game_update(keys):
    if _S["phase"] == "briefing":
        down = _advance_down(keys)
        if down and not _S["prev_advance"]:
            _S["line"] = _S["runner"].advance()
            if _S["runner"].ended or _S["line"] is None:
                _S["phase"] = "play"
        _S["prev_advance"] = down
        return (0, 0)
    if _S["phase"] != "play" or STATE.player is None:
        return (0, 0)
    _move_player(keys)
    px, py = STATE.player.rect.centerx, STATE.player.rect.centery
    for e in list(STATE.enemies):
        e.update(px, py, STATE.walls, STATE.bullets, STATE.particles)
    STATE.enemies = [e for e in STATE.enemies if e.hp > 0]
    _step_bullets()
    for pt in list(STATE.particles):
        pt.update()
    STATE.particles = [pt for pt in STATE.particles if pt.life > 0]
    if STATE.player.hp <= 0:
        start_mission0()          # fail -> restart (tutorial-simple)
        return (0, 0)
    for ex in _S["exit_rects"]:
        if STATE.player.rect.colliderect(ex):
            _S["phase"] = "done"
            _S["outro_requested"] = True
            break
    return (0, 0)


