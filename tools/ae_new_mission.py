class _Host:
    def flag(self, name):
        return bool(_S.get("flags", {}).get(name))

    def var(self, name):
        return _S.get("vars", {}).get(name)

    def set_var(self, name, value):
        _S.setdefault("vars", {})[name] = value

    def emit(self, name, payload=None):
        _S["last_event"] = (name, payload)

    def resolve(self, node):
        return node.get("text", "")

    def speaker_meta(self, speaker):
        return {}


