def _dump(path: str, data) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(data, indent=1, ensure_ascii=False) + "\n")


def _sub(text: str, mission: str, package: str, title: str) -> str:
    return (text.replace("__MISSION__", mission).replace("__PKG__", package)
            .replace("__TITLE__", title))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mission", help="content id stem, e.g. mission0")
    ap.add_argument("--package", required=True, help="python package, e.g. m0")
    ap.add_argument("--title", default="", help="display title")
    a = ap.parse_args()
    mission, package = a.mission, a.package
    title = a.title or f"{mission} - new mission"

    files = {
        f"src/game/content/levels/{mission}.depot.level.json":
            lambda p: _dump(p, json.loads(_sub(json.dumps(LEVEL), mission, package, title))),
        f"src/game/content/dialogue/{mission}.briefing.dlg.json":
            lambda p: _dump(p, json.loads(_sub(json.dumps(DIALOGUE), mission, package, title))),
        f"src/game/content/timelines/{mission}.outro.timeline.json":
            lambda p: _dump(p, json.loads(_sub(json.dumps(TIMELINE), mission, package, title))),
        f"src/game/content/sets/{mission}.depot.set3d.json":
            lambda p: _dump(p, json.loads(_sub(json.dumps(SET3D), mission, package, title))),
        f"src/missions/{package}/enemy_types.json":
            lambda p: _dump(p, json.loads(_sub(json.dumps(ENEMY_TYPES), mission, package, title))),
        f"src/missions/{package}/__init__.py":
            lambda p: open(p, "w", encoding="utf-8", newline="\n").write(
                _sub(HOST, mission, package, title)),
    }
    for rel, write in files.items():
        path = os.path.join(ROOT, rel)
        if os.path.exists(path):
            print(f"ae_new_mission: REFUSING to overwrite {rel}")
            return 1
        os.makedirs(os.path.dirname(path), exist_ok=True)
        write(path)
        print(f"created {rel}")
    upper = "".join(ch for ch in mission if ch.isdigit())
    print(f"""
Wire it up (game-side only - src/engine stays untouched):
  1. core/game_core.py: _is_mission{upper}_active() + start_{mission}() forwarder
     + branches in _mission_update()/game_draw() (host: missions.{package}).
  2. app.py: --dev-{mission} branch in _apply_dev_args; consume
     {package}.take_outro_request() in _GameState.update via start_cutscene.
  3. core/dev_jumps.py: "{package}": ("--dev-{mission}", "{title}").
Then: python tools/ae_validate.py && python acaristan.py --dev-{mission}
""")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
