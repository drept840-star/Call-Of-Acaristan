#!/usr/bin/env python3
"""Generate assets/import/barrel.obj - a low-poly barrel (10 sides,
bulged profile, two metal bands) as the Step-11 import fixture.

Deterministic; regenerate after editing, then re-import:
    python3 tools/gen_barrel_obj.py
    python3 tools/ae_import_mesh.py assets/import/barrel.obj barrel
"""
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "import", "barrel.obj")
N = 10
PROFILE = [(0.00, 0.30), (0.10, 0.325), (0.45, 0.345), (0.80, 0.325),
           (0.90, 0.30)]           # (y, radius) - bulged barrel
BANDS = [(0.16, 0.20, 0.352), (0.70, 0.74, 0.352)]  # (y0, y1, radius)


def ring(y, r):
    return [(r * math.cos(2 * math.pi * i / N), y,
             r * math.sin(2 * math.pi * i / N)) for i in range(N)]


def main():
    verts = []
    faces = []  # (indices, material)

    def add_ring(y, r):
        verts.extend(ring(y, r))
        return len(verts) - N  # first index (0-based) of the ring

    rings = [add_ring(y, r) for y, r in PROFILE]
    for a, b in zip(rings, rings[1:]):
        for i in range(N):
            j = (i + 1) % N
            faces.append(((a + i, b + i, b + j, a + j), "wood"))
    for y0, y1, r in BANDS:
        a, b = add_ring(y0, r), add_ring(y1, r)
        for i in range(N):
            j = (i + 1) % N
            faces.append(((a + i, b + i, b + j, a + j), "metal"))
    # caps: centre vertex + fan
    for y, flip in ((0.0, True), (0.90, False)):
        verts.append((0.0, y, 0.0))
        c = len(verts) - 1
        ring0 = rings[0] if flip else rings[-1]
        for i in range(N):
            j = (i + 1) % N
            faces.append(((c, ring0 + j, ring0 + i) if flip
                          else (c, ring0 + i, ring0 + j), "wood"))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# barrel - generated by tools/gen_barrel_obj.py\n")
        for v in verts:
            fh.write(f"v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}\n")
        cur = None
        for idx, mtl in faces:
            if mtl != cur:
                fh.write(f"usemtl {mtl}\n")
                cur = mtl
            fh.write("f " + " ".join(str(i + 1) for i in idx) + "\n")
    print(f"AE GEN BARREL: OK ({len(verts)} verts, {len(faces)} faces) "
          f"-> {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
