"""ae_star_imports - inventory of ``from core.config import *`` users (A-001 prep, Phase 4).

    python tools/ae_star_imports.py [--module core.config] [--md docs/engine/audit/star_imports.md]

For every module that star-imports ``core.config`` it lists the names that are
actually resolved through the star import (referenced in the module, exported
by core.config, not defined/imported locally) so the Phase 4 change can replace
each ``*`` with an explicit import line without guessing. AST + ``symtable`` -
nothing is imported or executed (core.config boots the display at import; R-no
side effects).
"""
from __future__ import annotations

import argparse
import ast
import builtins
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"


def exported_names(mod_path: Path) -> set[str]:
    """Names a `from M import *` binds (symtable: conditional module-level
    assignments count - B-019 follow-up: `bg_image` lives in an if/else and the
    old top-level AST walk never saw it)."""
    import symtable

    src = mod_path.read_text(encoding="utf-8", errors="replace")
    tree = ast.parse(src)
    all_ = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            try:
                all_ = set(ast.literal_eval(node.value))
            except ValueError:
                pass
    if all_ is not None:
        return all_
    st = symtable.symtable(src, str(mod_path), "exec")
    names = {s.get_name() for s in st.get_symbols()
             if s.is_assigned() or s.is_imported() or s.is_namespace() or s.is_annotated()}
    return {n for n in names if not n.startswith("_")}


def global_names(mod_path: Path) -> tuple[set[str], set[str]]:
    """(referenced globals, module-level bindings) via ``symtable`` - scope-correct.

    A function-local name never shadows the same name used as a global *elsewhere*
    in the file; the pre-2026-10-15 AST pass did not know that and silently dropped
    needed names from its `used` set (B-019: `WIDTH` / `screen` vanished from two M2
    modules and the golden M2 cuts died with NameError).
    """
    import symtable

    src = mod_path.read_text(encoding="utf-8", errors="replace")
    st = symtable.symtable(src, str(mod_path), "exec")
    bound = {s.get_name() for s in st.get_symbols()
             if s.is_assigned() or s.is_imported() or s.is_namespace() or s.is_annotated()}
    used: set[str] = set()

    def walk(t):
        for s in t.get_symbols():
            if s.is_referenced() and s.is_global() and not s.is_local():
                used.add(s.get_name())
        for child in t.get_children():
            walk(child)

    walk(st)
    return used, bound


def star_users(module: str) -> list[tuple[Path, int]]:
    out = []
    for p in sorted(SRC.rglob("*.py")):
        try:
            tree = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module == module and any(a.name == "*" for a in node.names):
                out.append((p, node.lineno))
    return out


def analyse(module: str):
    mod_path = SRC / (module.replace(".", "/") + ".py")
    exported = exported_names(mod_path)
    rows = []
    for p, line in star_users(module):
        tree = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
        # names bound by other star imports are unknown; keep it honest by listing them
        other_stars = [n.module for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)
                       and any(a.name == "*" for a in n.names) and n.module != module]
        g_used, g_bound = global_names(p)
        used = sorted((g_used - g_bound - set(dir(builtins))) & exported)
        rows.append({"file": p.relative_to(ROOT).as_posix(), "line": line, "used": used,
                     "other_stars": other_stars})
    return exported, rows


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--module", default="core.config")
    ap.add_argument("--md")
    args = ap.parse_args(argv)
    exported, rows = analyse(args.module)
    from collections import Counter
    freq = Counter(n for r in rows for n in r["used"])
    print(f"{args.module}: {len(exported)} exportable names; {len(rows)} star-import sites; "
          f"{len(freq)} distinct names actually used via *")
    for r in rows:
        print(f"  {r['file']}:{r['line']}  {len(r['used'])} names" + (f"  (other * imports: {r['other_stars']})" if r['other_stars'] else ""))
    if args.md:
        L = [f"# `from {args.module} import *` inventory (A-001 prep)", "",
             f"Generated by `python tools/ae_star_imports.py --md {args.md}` (AST + symtable). "
             f"`{args.module}` exposes **{len(exported)}** importable names; **{len(rows)}** modules star-import it and "
             f"between them use **{len(freq)}** distinct names through the star. Phase 4 replaces each `*` with the "
             f"explicit list below (one mechanical edit per file, parity-neutral; the gate is goldens + replay).", "",
             "## Most-used names", "", "| name | files |", "|---|---:|"]
        for n, c in freq.most_common(40):
            L.append(f"| `{n}` | {c} |")
        L += ["", "## Per file", ""]
        for r in rows:
            L.append(f"### `{r['file']}:{r['line']}` - {len(r['used'])} names")
            if r["other_stars"]:
                L.append(f"(also star-imports {', '.join('`' + s + '`' for s in r['other_stars'])}; names bound there are not visible to this pass)")
            L.append("")
            L.append("```python")
            L.append(f"from {args.module} import ({', '.join(r['used'])})" if r["used"] else f"# no {args.module} names used - drop the import")
            L.append("```")
            L.append("")
        Path(args.md).write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
        print("wrote", args.md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
