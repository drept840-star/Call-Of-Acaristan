_MISSING = GLYPHS[" "]


def _runs(glyph: tuple[str, ...]) -> list[tuple[int, int, int]]:
    """Merge each row's '#' into (col, row, length) runs."""
    out = []
    for row, line in enumerate(glyph):
        col = 0
        while col < GLYPH_W:
            if line[col] == "#":
                end = col
                while end + 1 < GLYPH_W and line[end + 1] == "#":
                    end += 1
                out.append((col, row, end - col + 1))
                col = end + 1
            else:
                col += 1
    return out


def layout(text, spacing=1):
    """Horizontal pixel runs for ``text`` on one line, with one box per run.

    Runs stop at the glyph edge so a sign can colour or light each letter
    separately later without a run straddling two.
    """
    runs = []
    advance = GLYPH_W + spacing
    for i, ch in enumerate(text.upper()):
        base = i * advance
        for col, row, length in _runs(GLYPHS.get(ch, _MISSING)):
            runs.append((base + col, row, length))
    return runs


def width(text, spacing=1):
    """Columns the text covers, without the trailing gap (0 for "")."""
    if not text:
        return 0
    return len(text) * (GLYPH_W + spacing) - spacing
