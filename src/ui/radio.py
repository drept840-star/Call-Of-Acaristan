"""Radio transmission widget (polish pass T6, field-radio restyle T6b).

One widget for every mission's radio traffic. The radio director in
``core.interactions`` decides WHAT is on air and WHEN (``live_line()``,
``radio_allowed()``, a pause-aware ``radio_clock()``); this module only
draws it:

* fixed bottom anchor in the free band right of the HP / weapon / molotov
  column (x >= 332) and left of the bottom-right edge markers, clear of
  the crosshair, minimap (top-right) and objective panel (top-left);
* drawn as a field radio set in the game's pixel-art style: gunmetal case
  with bevels and screws, a caller-ID screen with the speaker's pixel
  portrait (``assets/art/spr_portraits``, generated by
  ``tools/sprites/portraits.py``; integer nearest-neighbour scale only),
  speaker grille, recessed display glass with the callsign plate in the
  speaker's ``SPEAKER_COLORS`` accent, an LED signal ladder, RX lamp and an
  amber frequency readout (``mission_meta`` channel ``"NET // 141.20"``);
* bitmap pixel fonts (``ui.pixfont``, no TTF): word-wrapped body, at most
  3 rows visible (older rows scroll up and fade), typewriter paced to the VO
  clip (fixed readable rate without VO), block caret;
* slide + fade in (180 ms ease-out) with a short burst of static while the
  set "tunes in", fade out (250 ms), squelch in/out;
* signal LEDs only move while the VO channel is busy, faint scan band on
  the glass, queued-transmission LEDs, critical lines pulse the case edge
  and blink a red lamp;
* hidden instantly when the radio is blocked (cutscene / menu), frozen with
  the pause menu (all motion runs on the radio clock).

Settings (``PREFS``): radio text size (small / medium / large) and a
speaker-name toggle, persisted through ``core.settings_store``.
"""
