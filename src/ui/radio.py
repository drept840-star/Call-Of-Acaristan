def _screw(s, x, y, u):
    s.fill((112, 114, 104), (x, y, 2 * u, 2 * u))
    s.fill((150, 152, 140), (x, y, u, u))
    s.fill((40, 42, 38), (x + u, y + u, u, u))
    s.fill((60, 62, 56), (x, y + u, 2 * u, max(1, u // 2)))


def _bevel_box(s, rect, fill, hi, lo, u, inset=False):
    r = pygame.Rect(rect)
    s.fill(fill, r)
    a, b = (lo, hi) if inset else (hi, lo)
    s.fill(a, (r.x, r.y, r.w, u))
    s.fill(a, (r.x, r.y, u, r.h))
    s.fill(b, (r.x, r.bottom - u, r.w, u))
    s.fill(b, (r.right - u, r.y, u, r.h))


def _build_chassis(w, h, u, layout):
    s = pygame.Surface((w, h), pygame.SRCALPHA)
    # case: ink outline, olive gunmetal body, lit top-left / dark bottom-right
    s.fill((*CASE_INK, 255), (u, 0, w - 2 * u, h))
    s.fill((*CASE_INK, 255), (0, u, w, h - 2 * u))
    body = pygame.Rect(u, u, w - 2 * u, h - 2 * u)
    _bevel_box(s, body, CASE, CASE_HI, CASE_LO, u)
    # subtle brushed texture: a darker line every 3 units
    for y in range(body.y + 3 * u, body.bottom - 2 * u, 3 * u):
        s.fill(_mix(CASE, CASE_LO, 0.25), (body.x + u, y, body.w - 2 * u, max(1, u // 2)))
    for x, y in ((2 * u, 2 * u), (w - 4 * u, 2 * u), (2 * u, h - 4 * u), (w - 4 * u, h - 4 * u)):
        _screw(s, x, y, u)
    # caller-ID screen bezel
    scr = layout["screen"]
    _bevel_box(s, scr.inflate(2 * u, 2 * u), (8, 10, 9), CASE_LO, CASE_HI, u, inset=False)
    # speaker grille under the screen (when the set is tall enough)
    g = layout.get("grille")
    if g is not None:
        _bevel_box(s, g, _mix(CASE, CASE_LO, 0.4), CASE_LO, CASE_HI, u, inset=True)
        for yy in range(g.y + 2 * u, g.bottom - 2 * u + 1, 2 * u):
            for xx in range(g.x + 2 * u + ((yy - g.y) // (2 * u)) % 2 * u, g.right - 2 * u, 2 * u):
                s.fill(CASE_INK, (xx, yy, u, u))
    # recessed display glass
    win = layout["window"]
    _bevel_box(s, win.inflate(2 * u, 2 * u), GLASS, CASE_LO, CASE_HI, u, inset=False)
    s.fill(GLASS, win)
    s.fill(GLASS_HI, (win.x, win.y, win.w, u))
    for y in range(win.y + u, win.bottom, 2 * u):
        s.fill((14, 20, 16), (win.x, y, win.w, max(1, u // 2)))
    return s


def _screen_overlay(chip, u):
    """Scanlines + glass glint over the caller-ID screen (cached)."""
    key = ("scr", chip, u)
    hit = _chassis.get(key)
    if hit is None:
        hit = pygame.Surface((chip, chip), pygame.SRCALPHA)
        for y in range(u, chip, 2 * u):
            hit.fill((0, 0, 0, 46), (0, y, chip, max(1, u // 2)))
        hit.fill((255, 255, 255, 60), (u, u, u, 3 * u))
        hit.fill((255, 255, 255, 34), (2 * u, u, 2 * u, u))
        _chassis[key] = hit
    return hit


def _chassis_for(w, h, u, layout):
    key = (w, h, u, layout["screen"].topleft, layout.get("grille") is not None)
    hit = _chassis.get(key)
    if hit is None:
        if len(_chassis) > 32:
            _chassis.clear()
        hit = _chassis[key] = _build_chassis(w, h, u, layout)
    return hit


class RadioTransmission:
    """Stateful widget; one shared instance (``TRANSMISSION``)."""

    def __init__(self):
        self.cur = None          # dict copied from interactions.live_line()
        self.cur_key = None
        self.out_at = None       # radio-clock ms when the fade-out started
        self.history = []        # finished lines: dicts with 'done_at'
        self.log = []            # last 10 (speaker, body, color) for other UIs
        self.last_clock = 0

    # -- state ------------------------------------------------------------
    def reset(self):
        self.cur = None
        self.cur_key = None
        self.out_at = None
        self.history.clear()

    def _sync(self, live, allowed, clock):
        if not allowed:
            if self.cur is not None or self.history:
                self.reset()     # hard cut; the director already squelched
            return
        key = None if live is None else (live["start"], live["text"])
        if key != self.cur_key:
            if self.cur is not None:
                old = dict(self.cur)
                old["done_at"] = clock
                self.history.append(old)
                self.history = self.history[-2:]
            if live is not None:
                self.cur = dict(live)
                self.out_at = None
                self.log.append((live["speaker"], live["body"], live["color"]))
                self.log = self.log[-10:]
                if not live.get("vo_ms"):   # voiced clips carry their own squelch
                    _sfx("squelch_head", 0.22)
            else:
                self.cur = None
            self.cur_key = key
        if self.cur is not None and self.out_at is None and clock >= self.cur["end"]:
            self.out_at = clock
            if not self.cur.get("vo_ms"):
                _sfx("squelch_tail", 0.2)
        if self.cur is not None and self.out_at is not None and clock - self.out_at > OUT_MS:
            old = dict(self.cur)
            old["done_at"] = clock
            self.history.append(old)
            self.history = self.history[-2:]
            self.cur = None
        self.history = [h for h in self.history if clock - h["done_at"] < HISTORY_MS]

    # -- layout -----------------------------------------------------------
    @staticmethod
    def metrics(surface):
        """Geometry shared by draw() and the smoke test."""
        sw, sh = surface.get_size()
        scale = max(0.75, min(sw / WIDTH, sh / HEIGHT))
        u = unit_for(scale)
        f_body = body_font(PREFS.get("radio_text_size", 1), u)
        f_lab = _label_font(u)
        chip = PORTRAIT_PX * u
        pad = 4 * u
        panel_w = int(min(sw * 0.49, 490 * scale))
        win_x = pad + u + chip + u + 4 * u + u
        win_w = panel_w - win_x - pad - u
        text_w = win_w - 6 * u
        plate_h = (f_lab.cap + 2) * u
        head_h = plate_h + 2 * u
        return {"scale": scale, "u": u, "f_body": f_body, "f_lab": f_lab, "chip": chip,
                "pad": pad, "panel_w": panel_w, "win_x": win_x, "win_w": win_w,
                "text_w": text_w, "plate_h": plate_h, "head_h": head_h,
                "row_h": f_body.get_linesize()}

    @staticmethod
    def panel_height(m, n_rows):
        u = m["u"]
        win_h = 2 * u + m["head_h"] + n_rows * m["row_h"]
        return max(m["chip"] + 2 * u + 2 * m["pad"], win_h + 2 * u + 2 * m["pad"])

    # -- drawing ----------------------------------------------------------
    def draw(self, surface, live=None, allowed=True, clock=None, queued=0,
             channel=None, anchor="hud", bar_h=0, force_text=False):
        if clock is None:
            clock = self.last_clock
        self.last_clock = clock
        self._sync(live, allowed, clock)
        if self.cur is None and not self.history:
            return None
        sw, sh = surface.get_size()
        m = self.metrics(surface)
        scale = m["scale"]
        if anchor == "letterbox":
            x0 = (sw - m["panel_w"]) // 2
            one = self.panel_height(m, 1)
            bottom = sh - max(4, (bar_h - one) // 2)
        else:
            x0 = int(HUD_ANCHOR_X * scale)
            bottom = sh - int(HUD_ANCHOR_BOTTOM * scale)
        drawn = None
        # history rows (compact, one line each) stacked above the live panel
        stack_y = bottom
        if self.cur is not None:
            rect = self._draw_live(surface, self.cur, clock, x0, bottom, m, queued,
                                   channel, force_text)
            drawn = rect
            stack_y = rect.top - int(4 * scale)
        # letterbox: one line only, history would stack into the picture
        for h in (() if anchor == "letterbox" else reversed(self.history)):
            age = clock - h["done_at"]
            a = int(150 * max(0.0, 1.0 - age / HISTORY_MS))
            if a <= 6:
                continue
            stack_y = self._draw_history(surface, h, x0, stack_y, m, a)
        return drawn

    def _draw_history(self, surface, h, x0, bottom, m, alpha):
        u, font, panel_w = m["u"], m["f_lab"], m["panel_w"]
        acc = accent_for(h["speaker"], h["color"])
        name = _base(h["speaker"]) if PREFS.get("radio_speaker_names", True) else ""
        body = (h["body"] or "").replace("\n", " ")
        name_w = font.size(name)[0] + 3 * u if name else 0
        room = panel_w - 8 * u - name_w
        while font.size(body)[0] > room and len(body) > 4:
            body = body[:-5] + "\u2026"
        hgt = (font.rows + 2) * u
        s = pygame.Surface((panel_w, hgt), pygame.SRCALPHA)
        s.fill((14, 16, 13, int(alpha * 0.85)))
        s.fill((*CASE_LO, alpha), (0, hgt - u, panel_w, u))
        s.fill((*acc, alpha), (0, 0, u, hgt))
        x = 3 * u
        if name:
            t = font.render(name, False, acc)
            t.set_alpha(alpha)
            s.blit(t, (x, u))
            x += name_w
        t = font.render(body, False, HIST_RGB)
        t.set_alpha(alpha)
        s.blit(t, (x, u))
        surface.blit(s, (x0, bottom - hgt))
        return bottom - hgt - u

    def _draw_live(self, surface, cur, clock, x0, bottom, m, queued, channel, force_text):
        u, chip, pad = m["u"], m["chip"], m["pad"]
        f_body, f_lab = m["f_body"], m["f_lab"]
        panel_w, row_h = m["panel_w"], m["row_h"]
        acc = accent_for(cur["speaker"], cur["color"])
        age = clock - cur["start"]
        a_in = _ease_out(age / IN_MS)
        a_out = 1.0
        slide = (1.0 - a_in) * -26
        if self.out_at is not None:
            k = min(1.0, (clock - self.out_at) / OUT_MS)
            a_out = 1.0 - k
            slide += -10 * k
        alpha = max(0.0, min(1.0, a_in * a_out))
        show_text = force_text or PREFS.get("subtitles", True) or not cur.get("vo_ms")
        body = cur["body"] or ""
        rows = _wrap(body, f_body, m["text_w"]) if show_text else []
        # typewriter, paced to the clip when there is one
        vo = cur.get("vo_ms") or 0
        type_ms = vo * 0.92 if vo else max(1, len(body)) * TYPE_MS_PER_CHAR
        n_vis = len(body) if type_ms <= 0 else int(len(body) * min(1.0, age / type_ms))
        vis_rows, left = [], n_vis
        for r in rows:
            if left <= 0:
                break
            vis_rows.append(r[:left])
            left -= len(r) + 1
        scrolled = max(0, len(vis_rows) - MAX_ROWS)
        vis_rows = vis_rows[scrolled:]
        n_rows = max(1, min(MAX_ROWS, len(rows))) if show_text else 0
        panel_h = self.panel_height(m, n_rows)

        # layout (panel-local px)
        screen = pygame.Rect(pad + u, pad + u, chip, chip)
        grille = None
        g_top = screen.bottom + 3 * u
        if panel_h - pad - g_top >= 7 * u:
            grille = pygame.Rect(screen.x - u, g_top, chip + 2 * u, panel_h - pad - g_top)
        win = pygame.Rect(m["win_x"], pad + u, m["win_w"], panel_h - 2 * pad - 2 * u)
        layout = {"screen": screen, "window": win, "grille": grille}
        s = _chassis_for(panel_w, panel_h, u, layout).copy()

        crit = (cur.get("priority") or 0) >= 1
        busy = _vo_busy() and vo > 0 and self.out_at is None
        tuning = age < STATIC_MS
        # critical: the case edge flashes in the accent, once
        if crit and age < PULSE_MS:
            p = math.sin(math.pi * age / PULSE_MS)
            ring = pygame.Surface((panel_w, panel_h), pygame.SRCALPHA)
            pygame.draw.rect(ring, (*acc, int(90 + 160 * p)), ring.get_rect(), max(u, int(u * (1 + 2 * p))))
            s.blit(ring, (0, 0))

        # caller-ID screen: accent-tinted CRT, portrait, scanlines, glass glint
        s.fill(_mix(acc, (6, 8, 8), 0.82), screen)
        if not tuning or age > STATIC_MS * 0.55:
            s.blit(_portrait(cur["speaker"], chip, acc), screen.topleft)
        s.blit(_screen_overlay(chip, u), screen.topleft)

        # header inside the glass: callsign plate, LED ladder, RX lamp,
        # amber frequency readout with queue LEDs
        hx, hy = win.x + 3 * u, win.y + 2 * u
        plate_h = m["plate_h"]
        if PREFS.get("radio_speaker_names", True) and cur["speaker"]:
            name = _base(cur["speaker"])
            nw = f_lab.size(name)[0]
            plate = pygame.Rect(hx, hy, nw + 4 * u, plate_h)
            s.fill(acc, plate)
            s.fill(_mix(acc, (255, 255, 255), 0.35), (plate.x, plate.y, plate.w, u))
            s.fill(_mix(acc, (0, 0, 0), 0.35), (plate.x, plate.bottom - u, plate.w, u))
            f_lab.draw(s, name, (plate.x + 2 * u, plate.y + u), (14, 14, 16))
            hx = plate.right + 3 * u
        seg_rows = max(3, (plate_h // u - 1) // 2)
        for i in range(6):
            if busy:
                lv = 0.25 + 0.75 * abs(math.sin(clock * (0.011 + i * 0.0037) + i * 1.7)
                                      * math.sin(clock * 0.0047 + i))
            else:
                lv = 0.0
            lit = int(round(lv * seg_rows))
            for j in range(seg_rows):
                on = j < lit
                col = (LED_RED if j == seg_rows - 1 else acc) if on else LED_OFF
                s.fill(col, (hx + i * 2 * u, hy + plate_h - (j + 1) * 2 * u + u, u, u))
        hx += 12 * u + u
        # RX lamp: green while receiving, red blink for critical traffic
        on_air = self.out_at is None
        lamp = LED_OFF
        if on_air:
            lamp = LED_RED if (crit and (clock // 180) % 2 == 0) else LED_GREEN
        rx = f_lab.render(_T("radio.rx"), False, (120, 130, 118))
        ly = hy + (plate_h - rx.get_height()) // 2 + u
        s.blit(rx, (hx, ly))
        s.fill(lamp, (hx + rx.get_width() + u, hy + plate_h // 2 - u, 2 * u, 2 * u))
        if on_air:
            s.fill(_mix(lamp, (255, 255, 255), 0.5), (hx + rx.get_width() + u, hy + plate_h // 2 - u, u, u))
        hx += rx.get_width() + 4 * u
        net, freq = _split_channel(channel or _channel_label())
        qn = min(3, queued)
        right = win.right - 3 * u
        for i in range(qn):
            s.fill(AMBER, (right - 2 * u - i * 3 * u, hy + plate_h // 2 - u, 2 * u, 2 * u))
        if qn:
            right -= qn * 3 * u + 2 * u
        if freq:
            ft = f_lab.render(freq, False, AMBER)
            box = pygame.Rect(right - ft.get_width() - 4 * u, hy, ft.get_width() + 4 * u, plate_h)
            if box.x > hx:
                s.fill(AMBER_BG, box)
                s.fill(_mix(AMBER_BG, (0, 0, 0), 0.5), (box.x, box.y, box.w, u))
                s.blit(ft, (box.x + 2 * u, box.y + u))
                right = box.x - 2 * u
        if net:
            nt = f_lab.render(net, False, (118, 128, 118))
            if right - nt.get_width() > hx:
                s.blit(nt, (right - nt.get_width(), hy + u))

        # body rows: phosphor text with a 1-unit drop shadow; first row fades
        tx, by = win.x + 3 * u, hy + m["head_h"]
        for i, r in enumerate(vis_rows):
            ra = 120 if (scrolled and i == 0) else 255
            t = f_body.render(r, False, BODY_RGB)
            sh_ = f_body.render(r, False, (0, 0, 0))
            if ra != 255:
                t = t.copy()
                t.set_alpha(ra)
                sh_ = sh_.copy()
                sh_.set_alpha(ra)
            s.blit(sh_, (tx + u // 2 or 1, by + i * row_h + (u // 2 or 1)))
            s.blit(t, (tx, by + i * row_h))
        if show_text and n_vis < len(body) and (clock // 220) % 2 == 0 and vis_rows:
            last = vis_rows[-1]
            cxp = tx + f_body.size(last)[0] + f_body.scale
            s.fill(acc, (cxp, by + (len(vis_rows) - 1) * row_h,
                         f_body.scale * 3, f_body.get_ascent()))

        # scan band drifting down the glass
        band_h = 4 * u
        band_y = win.y + int((clock * 0.05) % (win.h + band_h * 2)) - band_h
        bt, bb = max(win.y, band_y), min(win.bottom, band_y + band_h)
        if bb > bt:
            band = pygame.Surface((win.w, bb - bt), pygame.SRCALPHA)
            band.fill((180, 255, 200, 10))
            s.blit(band, (win.x, bt))

        # static burst while the set tunes in (screen + glass). The burst is a pure
        # function of (40 ms clock bucket, body length, fade step, geometry), so it is
        # cached (RPE6 Phase 6 bench: this was the hottest HUD cost) - same pixels.
        if tuning:
            k = 1.0 - age / STATIC_MS
            alpha_v = int(200 * k)
            ns = (int(screen.w * screen.h / (u * u) * 0.55 * k),
                  int(win.w * win.h / (u * u) * 0.22 * k))
            key = (panel_w, panel_h, u, screen.topleft, screen.size, win.topleft, win.size,
                   int(clock // 40), len(body), ns, alpha_v)
            noise = _noise.get(key)
            if noise is None:
                if len(_noise) > 32:
                    _noise.clear()
                rng = random.Random(int(clock // 40) * 7919 + len(body))
                noise = pygame.Surface((panel_w, panel_h), pygame.SRCALPHA)
                for (area, _dens), n in zip(((screen, 0.55), (win, 0.22)), ns):
                    for _ in range(n):
                        nx = area.x + rng.randrange(0, max(1, area.w // u)) * u
                        ny = area.y + rng.randrange(0, max(1, area.h // u)) * u
                        v = rng.randrange(60, 230)
                        noise.fill((v, v, v, alpha_v), (nx, ny, u, u))
                _noise[key] = noise
            s.blit(noise, (0, 0))

        s.set_alpha(int(255 * alpha))
        surface.blit(s, (x0 + int(slide), bottom - panel_h))
        return pygame.Rect(x0, bottom - panel_h, panel_w, panel_h)


