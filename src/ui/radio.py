def _portrait_source(speaker, accent):
    """24x24 source portrait: hand-made PNG override > generated sheet > fallback."""
    name = _base(speaker).lower().replace(" ", "_")
    path = os.path.join(_ROOT, "assets", "sprites", "portraits", name + ".png")
    if name and os.path.exists(path):
        try:
            img = _load_image(path)
            if pygame.display.get_surface() is not None:
                img = img.convert_alpha()
            return img
        except Exception:
            pass
    try:
        from core import artpack
        img = artpack.frame("spr_portraits", portrait_key(speaker))
        if img is None and portrait_key(speaker) != "unknown":
            img = artpack.frame("spr_portraits", "unknown")
        if img is not None:
            return img
    except Exception:
        pass
    return None


def _fallback_portrait(accent):
    """Procedural caller in the same 24 px grid: shadowed head + headset."""
    s = pygame.Surface((PORTRAIT_PX, PORTRAIT_PX), pygame.SRCALPHA)
    body = _mix(accent, (40, 44, 48), 0.6)
    lit = _mix(accent, (90, 96, 100), 0.5)
    for y, (x0, x1) in {18: (6, 17), 19: (4, 19)}.items():
        s.fill(body, (x0, y, x1 - x0 + 1, 1))
    s.fill(body, (2, 20, 20, 4))
    s.fill(body, (10, 15, 4, 4))
    s.fill(lit, (7, 5, 10, 10))
    s.fill(lit, (8, 4, 8, 12))
    s.fill(lit, (9, 15, 6, 1))
    s.fill((40, 42, 46), (9, 10, 2, 1))
    s.fill((40, 42, 46), (13, 10, 2, 1))
    s.fill((58, 62, 66), (7, 2, 10, 1))
    s.fill((58, 62, 66), (4, 8, 3, 4))
    return s


def _portrait(speaker, size, accent):
    """Portrait at an integer multiple of the 24 px source (nearest only)."""
    key = (_base(speaker), size, tuple(accent))
    hit = _portraits.get(key)
    if hit is not None:
        return hit
    src = _portrait_source(speaker, accent)
    cache = src is not None or os.environ.get("ACA_ART", "") in ("legacy", "off")
    if src is None:      # sheet missing / no display yet: don't pin the fallback
        src = _fallback_portrait(accent)
    w, h = src.get_size()
    k = max(1, size // max(1, w))
    surf = pygame.transform.scale(src, (w * k, h * k)) if k != 1 else src.copy()
    if surf.get_size() != (size, size):
        out = pygame.Surface((size, size), pygame.SRCALPHA)
        out.blit(surf, ((size - surf.get_width()) // 2, size - surf.get_height()))
        surf = out
    if cache:
        _portraits[key] = surf
    return surf


def _ease_out(x):
    x = max(0.0, min(1.0, x))
    return 1.0 - (1.0 - x) ** 3


