# name -> (glyph table, cap rows, total rows incl. descenders, line gap)
FONTS = {"R7": (_R7, 7, 9, 2), "R5": (_R5, 5, 7, 2)}

_MAP = {"\u2018": "'", "\u2019": "'", "\u201a": ",", "\u201c": '"', "\u201d": '"',
        "\u201e": '"', "\u2013": "-", "\u2212": "-", "\u00a0": " ", "\t": " ",
        "\u00ab": '"', "\u00bb": '"', "\u2022": "*", "\u00b7": "."}

_RUNS = {}


def _runs(name, ch):
    """Glyph as (width, [(row, x0, length), ...]) horizontal ink runs."""
    key = (name, ch)
    hit = _RUNS.get(key)
    if hit is not None:
        return hit
    table = FONTS[name][0]
    rows = table[ch].split("|")
    w = max(len(r) for r in rows)
    runs = []
    for y, r in enumerate(rows):
        x = 0
        while x < len(r):
            if r[x] == "#":
                x0 = x
                while x < len(r) and r[x] == "#":
                    x += 1
                runs.append((y, x0, x - x0))
            else:
                x += 1
    hit = (w, runs)
    _RUNS[key] = hit
    return hit


def fold(text, name="R7"):
    """Map text onto the glyph set (accents stripped, quotes/dashes folded)."""
    table = FONTS[name][0]
    out = []
    for ch in text or "":
        if ch in table:
            out.append(ch)
            continue
        ch = _MAP.get(ch, ch)
        if ch in table:
            out.append(ch)
            continue
        base = "".join(c for c in unicodedata.normalize("NFKD", ch)
                       if not unicodedata.combining(c))
        if base and all(c in table for c in base):
            out.append(base)
        elif ch in ("\n", "\r"):
            out.append(" ")
        else:
            out.append("?")
    return "".join(out)


class PixelFont:
    """Integer-scaled bitmap font with a ``pygame.font.Font``-like surface."""

    def __init__(self, name="R7", scale=2, bold=False, tracking=1):
        self.name = name
        self.scale = max(1, int(scale))
        self.bold = bool(bold)
        self.tracking = tracking
        _t, self.cap, self.rows, self.gap = FONTS[name]
        self._cache = {}

    # -- metrics (all in output pixels) ---------------------------------
    def _adv(self, ch):
        w, _r = _runs(self.name, ch)
        return w + self.tracking + (1 if self.bold else 0)

    def size(self, text):
        t = fold(text, self.name)
        if not t:
            return (0, self.get_height())
        units = sum(self._adv(c) for c in t) - self.tracking
        return (max(0, units) * self.scale, self.get_height())

    def get_height(self):
        return self.rows * self.scale

    def get_linesize(self):
        return (self.rows + self.gap) * self.scale

    def get_ascent(self):
        return self.cap * self.scale

    # -- drawing ---------------------------------------------------------
    def draw(self, surface, text, pos, color):
        """Draw straight onto ``surface`` (no intermediate surface)."""
        t = fold(text, self.name)
        k = self.scale
        x, y0 = int(pos[0]), int(pos[1])
        col = tuple(color)
        for ch in t:
            w, runs = _runs(self.name, ch)
            for ry, rx, rl in runs:
                surface.fill(col, (x + rx * k, y0 + ry * k, (rl + (1 if self.bold else 0)) * k, k))
            x += self._adv(ch) * k
        return x - int(pos[0])

    def render(self, text, antialias=False, color=(255, 255, 255), background=None):
        key = (text, tuple(color), background)
        hit = self._cache.get(key)
        if hit is not None:
            return hit
        w, h = self.size(text)
        surf = pygame.Surface((max(1, w), h), pygame.SRCALPHA)
        if background is not None:
            surf.fill(background)
        self.draw(surf, text, (0, 0), (*tuple(color)[:3], 255) if len(color) == 3 else color)
        if len(self._cache) > 384:
            self._cache.clear()
        self._cache[key] = surf
        return surf


_FONTS = {}


def font(name="R7", scale=2, bold=False):
    """Shared cached PixelFont instance."""
    key = (name, int(scale), bool(bold))
    f = _FONTS.get(key)
    if f is None:
        f = _FONTS[key] = PixelFont(name, scale, bold)
    return f
