"""Pixel bitmap fonts for the radio UI (polish pass T6b).

Two hand-authored proportional fonts, drawn with integer-scaled square
pixels only (no anti-aliasing, no TTF), so radio text matches the game's
pixel-art sprites at any window scale:

* ``R7`` - 7 px cap height, 5 px x-height, 2 px descenders, mixed case.
  Body text (medium / large radio text sizes).
* ``R5`` - 5 px cap height, 4 px x-height, mixed case. Labels, callsigns,
  history rows and the small radio text size.

``PixelFont(name, scale, bold)`` mimics the bit of the ``pygame.font.Font``
API the UI uses: ``render(text, aa, color)``, ``size(text)``,
``get_linesize()``, ``get_height()``. Unknown characters are folded to
ASCII (accents stripped, smart quotes / dashes mapped) or drawn as ``?``.
Glyph rows: ``#`` = ink, ``.`` = empty; row 0 is the cap/ascender line.
"""
